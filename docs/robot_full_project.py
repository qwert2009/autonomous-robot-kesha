def print_budget():
    total_usd = 0
    total_tmm = 0
    from_file = []
    from_china = []
    print("\n" + "=" * 70)
    print("БЮДЖЕТ")
    print("=" * 70)

    for name, info in COMPONENTS.items():
        usd = info.get("цена_usd", 0)
        tmm = info.get("цена_tmm", 0)
        total_usd += usd
        total_tmm += tmm
        source = info.get("источник", "")
        if "Файл" in source:
            from_file.append((name, tmm, usd))
        else:
            from_china.append((name, usd))

    print("\n📦 ИЗ ФАЙЛА (местный магазин, ТММ):")
    print("-" * 50)
    file_tmm = 0
    file_usd = 0
    for name, tmm, usd in from_file:
        print(f"  {name:50s} {tmm:>6} ТММ  (~${usd:.2f})")
        file_tmm += tmm
        file_usd += usd
    print(f"  {'ИТОГО':50s} {file_tmm:>6} ТММ  (~${file_usd:.2f})")

    print("\n🇨🇳 ИЗ КИТАЯ (AliExpress):")
    print("-" * 50)
    china_usd = 0
    for name, usd in from_china:
        print(f"  {name:50s} ${usd:.2f}")
        china_usd += usd
    print(f"  {'ИТОГО':50s} ${china_usd:.2f}")

    print(f"\n{'=' * 70}")
    print(f"  ОБЩИЙ БЮДЖЕТ: ${total_usd:.2f}")
    print(f"  Из файла:     {file_tmm} ТММ (~${file_usd:.2f})")
    print(f"  Из Китая:     ${china_usd:.2f}")
    print(f"{'=' * 70}")


